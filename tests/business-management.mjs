import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
const db = new PGlite();
await db.exec(`
CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth; CREATE SCHEMA private;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
CREATE FUNCTION private.is_active_account(uuid) RETURNS boolean LANGUAGE sql AS $$ SELECT $1 IS NOT NULL $$;
CREATE FUNCTION private.is_revmate_admin(uuid) RETURNS boolean LANGUAGE sql AS $$ SELECT false $$;
GRANT USAGE ON SCHEMA public,auth,private TO anon,authenticated;
CREATE TABLE public.businesses(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),name text,owner_user_id uuid,verified boolean DEFAULT false,status text DEFAULT 'active',promoted_until timestamptz,created_at timestamptz DEFAULT now(),logo_url text);
GRANT SELECT,INSERT,UPDATE ON public.businesses TO authenticated;
ALTER TABLE public.businesses ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_read ON public.businesses FOR SELECT TO authenticated USING (owner_user_id=auth.uid());
CREATE POLICY own_update ON public.businesses FOR UPDATE TO authenticated USING (owner_user_id=auth.uid()) WITH CHECK(owner_user_id=auth.uid());
CREATE FUNCTION private.guard_business_owner_edit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END; $$;
CREATE TRIGGER guard_business_owner_edit BEFORE UPDATE ON public.businesses FOR EACH ROW EXECUTE FUNCTION private.guard_business_owner_edit();
`);
await db.exec(await readFile("drizzle/migrations/0071_member_business_management.sql", "utf8"));
const owner = "00000000-0000-0000-0000-000000000001", other = "00000000-0000-0000-0000-000000000002";
await db.exec(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub','${owner}',false);`);
const { rows } = await db.query("INSERT INTO businesses(name,owner_user_id,contact_name) VALUES('Demo business',$1,'Kev') RETURNING id", [owner]);
const id = rows[0].id;
assert.ok(id, "A member can create their own business");
await assert.rejects(() => db.query("INSERT INTO businesses(name,owner_user_id) VALUES('Not mine',$1)", [other]));
await assert.rejects(() => db.query("INSERT INTO businesses(name,owner_user_id,verified) VALUES('Fake verified',$1,true)", [owner]));
await db.query("UPDATE businesses SET name='Updated demo',contact_name='Kevin',logo_url='https://example.test/logo.jpg',verified=true,status='suspended',owner_user_id=$2 WHERE id=$1", [id, other]);
const result = (await db.query("SELECT * FROM businesses WHERE id=$1", [id])).rows[0];
assert.equal(result.name, "Updated demo"); assert.equal(result.contact_name, "Kevin"); assert.equal(result.logo_url, "https://example.test/logo.jpg");
assert.equal(result.verified, false); assert.equal(result.status, "active"); assert.equal(result.owner_user_id, owner);
await db.exec(`SELECT set_config('request.jwt.claim.sub','${other}',false);`);
assert.equal((await db.query("UPDATE businesses SET name='Hijack' WHERE id=$1 RETURNING id", [id])).rows.length, 0);
await db.exec("RESET ROLE; SET ROLE anon;");
await assert.rejects(() => db.query("INSERT INTO businesses(name,owner_user_id) VALUES('Anonymous',$1)", [owner]));
await db.close(); console.log("Business creation, ownership, contact/logo editing and protected status checks passed.");